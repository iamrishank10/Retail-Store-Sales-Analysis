-- Question 1. What is the total revenue generated by the store?

select sum(total_amount) as total_revenue
from orders;

-- Question 2. How many orders has the store received?

select count(order_id) as Count_of_Orders
from orders;

-- Question 3. Which products are available in the store?

select product_name from products;

-- Question 4. Which products have a price greater than ₹5,000?

select product_name,price from products
where price > 5000;

-- Question 5. How much revenue has each product generated?

select p.product_name,sum(total_amount) as total_revenue
from products p
join orders o
on p.product_id = o.product_id
group by p.product_id
order by total_revenue desc;

-- Question 6. Which product category generates the highest revenue?

select p.category,sum(total_amount) as total_revenue
from products p
join orders o
on p.product_id = o.product_id
group by p.category
order by total_revenue desc
limit 1;

-- Question 7. How many orders has each customer placed?

select c.customer_name,count(o.order_id) as total_orders
from customers c
join orders o
on c.customer_id = o.customer_id
group by c.customer_id
order by total_orders desc;

-- Question 8. Which city generates the highest revenue?

select c.city,sum(o.total_amount) as total_revenue
from customers c
join orders o
on c.customer_id = o.customer_id
group by c.city
order by total_revenue desc
limit 1;

-- Question 9. What is the total quantity of products sold?

select sum(quantity) as units_sold
from orders;

-- Question 10. What is the monthly revenue of the store?

select 
year(order_date) as sales_year,
month(order_date) as sales_month,
sum(total_amount) as revenue
from orders
group by sales_year,sales_month
order by sales_year,sales_month;
