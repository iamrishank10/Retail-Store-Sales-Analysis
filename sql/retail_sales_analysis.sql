-- Question 23. How can we display each order along with the customer name and product name?

SELECT o.order_id, c.customer_name, p.product_name, o.quantity, o.total_amount
FROM orders o INNER JOIN customers c
ON o.customer_id = c.customer_id
INNER JOIN products p ON o.product_id = p.product_id;

-- Question 24. How can we display all customers, including those who have never placed an order?

SELECT c.customer_id, c.customer_name, o.order_id
FROM customers c LEFT JOIN orders o
ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- Question 25. How can we display all customers and their orders, including customers without orders?

SELECT c.customer_name, o.order_id, o.total_amount
FROM orders o
RIGHT JOIN customers c
ON o.customer_id = c.customer_id;

-- Question 26. How can we generate every possible combination of customers and products?

SELECT c.customer_name, p.product_name
FROM customers c
CROSS JOIN products p;

-- Question 27. How can we identify customers whose total spending exceeds ₹40,000 using a CTE?

WITH customer_spending AS (
SELECT customer_id, SUM(total_amount) AS total_spending
FROM orders
GROUP BY customer_id
)
SELECT c.customer_name, cs.total_spending
FROM customer_spending cs
JOIN customers c
ON cs.customer_id = c.customer_id
WHERE cs.total_spending > 40000;

-- Question 28. How can we number orders from highest to lowest by order amount?

SELECT order_id, total_amount,
ROW_NUMBER() OVER (ORDER BY total_amount DESC) AS row_num
FROM orders;

-- Question 29. How can we rank orders by total amount while giving equal amounts the same rank?

SELECT order_id, total_amount,
RANK() OVER (ORDER BY total_amount DESC) AS order_rank
FROM orders;

-- Question 30. How can we rank orders without skipping rank numbers when amounts are equal?

SELECT order_id, total_amount,
DENSE_RANK() OVER (ORDER BY total_amount DESC) AS dense_rank_num
FROM orders;

-- Question 31. How can we compare each customer's order amount with their previous order?

SELECT customer_id, order_id, order_date, total_amount,
LAG(total_amount) OVER (PARTITION BY customer_id ORDER BY order_date) AS previous_order_amount
FROM orders;

-- Question 32. How can we display the next order amount for each customer?

SELECT customer_id, order_id, order_date, total_amount,
LEAD(total_amount) OVER (PARTITION BY customer_id ORDER BY order_date) AS next_order_amount
FROM orders;

-- Question 33. How can we display the first order amount for every customer on all their order rows?

SELECT customer_id, order_id, order_date, total_amount,
FIRST_VALUE(total_amount) OVER (PARTITION BY customer_id ORDER BY order_date
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS first_order_amount
FROM orders;

-- Question 34. How can we display the last order amount for every customer on all their order rows?

SELECT customer_id, order_id, order_date, total_amount,
LAST_VALUE(total_amount) OVER (PARTITION BY customer_id ORDER BY order_date
ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS last_order_amount
FROM orders;

-- Question 35. How can we calculate a running total of order revenue over time?

SELECT order_id, order_date, total_amount,
SUM(total_amount) OVER (ORDER BY order_date, order_id
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_revenue
FROM orders;
